# Writes src/styles/scopes.css: finds every rule whose background is lime,
# amber or the feature colour (teal in light, white in dark) and puts its
# selectors in the matching ink scope from tokens.css, keeping any @media.
# Quiet grounds (surface-2/3 with no line) get a solid outline instead.
import re, glob, os
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'styles'))
files = ['base.css', 'shell.css'] + sorted(f for f in glob.glob('screens/*.css'))
LIME = r'background(?:-color)?:\s*var\(--(lime|lime-strong|accent-wash)\)'
AMB = r'background(?:-color)?:\s*var\(--(warm|warm-wash)\)'
NAVY = r'background(?:-color)?:\s*var\(--(navy|navy-2)\)'
Q = r'background(?:-color)?:\s*var\(--(surface-2|surface-3)\)'
groups = {}  # (media, kind) -> [selectors]
order = []

def rules(css, media=''):
    i = 0
    while True:
        j = css.find('{', i)
        if j < 0: return
        head = ' '.join(css[i:j].split())
        depth, k = 1, j + 1
        while depth:
            if css[k] == '{': depth += 1
            elif css[k] == '}': depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        if head.startswith('@media') or head.startswith('@supports'):
            yield from rules(body, head)
        elif not head.startswith('@'):
            yield media, head, body
        i = k

def add(media, kind, sels):
    key = (media, kind)
    if key not in groups: groups[key] = []; order.append(key)
    groups[key] += sels

for f in files:
    css = re.sub(r'/\*.*?\*/', '', open(f).read(), flags=re.S)
    for media, sel, body in rules(css):
        sels = [s.strip() for s in sel.split(',')]
        if re.search(LIME, body) and 'var(--on-lime)' not in body: add(media, 'lime', sels)
        if re.search(AMB, body) and 'var(--on-warm)' not in body: add(media, 'amber', sels)
        if re.search(NAVY, body): add(media, 'navy', sels)
        if re.search(Q, body) and not re.search(r'border(-color)?:[^;]*var\(--(line|line-strong|accent-line)\)|inset', body): add(media, 'quiet', sels)

tok = open('tokens.css').read()
decl = {k: tok.split(f'.on-{k} {{')[1].split('}')[0] for k in ['lime', 'amber', 'navy']}
decl['quiet'] = '\n  outline: 1.5px solid var(--line);\n  outline-offset: -1.5px;\n'
out = '''/* Generated by scripts/palette-scopes.py (do not edit by hand; run
   python3 scripts/palette-scopes.py after changing a background): which parts sit on
   lime, amber or the feature colour, and which quiet grounds get a solid line
   instead of a grey. The ink inside each follows tokens.css (.on-lime,
   .on-amber, .on-navy). Each rule keeps the @media it came from. */
'''
for kind in ['quiet', 'amber', 'lime', 'navy']:
    for key in order:
        if key[1] != kind: continue
        sels = ',\n'.join(dict.fromkeys(groups[key]))
        block = sels + ' {' + decl[kind] + '}\n'
        if key[0]:
            block = key[0] + ' {\n' + '\n'.join('  ' + l if l else l for l in block.splitlines()) + '\n}\n'
        out += '\n' + block
open('scopes.css', 'w').write(out)
print({k: len(v) for k, v in groups.items()})
